import { performance } from "node:perf_hooks";
import { writeFileSync } from "node:fs";
import { createWorkspace } from "../src/state/workspace.ts";
import { createLiveValue } from "../src/state/liveValue.ts";

const workspace = createWorkspace();
workspace.actions.addRows(999);
const rows = workspace.store.get(workspace.rows);
let rowNotifications = 0;
let listNotifications = 0;
let summaryNotifications = 0;
const cleanups = rows.map((row) => workspace.store.sub(row.level.value, () => rowNotifications++));
cleanups.push(workspace.store.sub(workspace.rows, () => listNotifications++));
cleanups.push(workspace.store.sub(workspace.errorCount, () => summaryNotifications++));
const start = performance.now();
for (let i = 0; i < 10_000; i++) workspace.store.set(rows[i % rows.length].level.value, String(Math.floor(i / 1_000)));
const editMs = performance.now() - start;
const editedNotifications = rowNotifications;
rowNotifications = 0;
const broadcastStart = performance.now();
workspace.actions.broadcastLevel("invalid");
const broadcastMs = performance.now() - broadcastStart;
const broadcastNotifications = rowNotifications;
let frameCallback: (() => void) | undefined;
let scheduledFrames = 0;
let liveNotifications = 0;
const channel = createLiveValue({ request(callback) { scheduledFrames++; frameCallback = callback; return 1; }, cancel() { frameCallback = undefined; } });
const stop = channel.subscribe(() => liveNotifications++);
for (let i = 1; i <= 10_000; i++) channel.publish(i);
frameCallback?.();
const report = { node: process.version, date: new Date().toISOString(), rows: rows.length, editMs: Number(editMs.toFixed(2)), edits: 10_000, editedNotifications, listNotifications, broadcastMs: Number(broadcastMs.toFixed(2)), broadcastNotifications, summaryNotifications, liveMessages: 10_000, scheduledFrames, liveNotifications, latestDisplay: channel.getSnapshot() };
console.table(report);
writeFileSync(new URL("./workspace-results.json", import.meta.url), `${JSON.stringify(report, null, 2)}\n`);
stop(); cleanups.forEach((cleanup) => cleanup());
